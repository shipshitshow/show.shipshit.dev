#!/usr/bin/env python3
"""Generate web theme from the approved vault contract and reject known brand drift."""
from pathlib import Path
import argparse
import json
import hashlib
import re
import xml.etree.ElementTree as ET

parser = argparse.ArgumentParser()
parser.add_argument('--source', type=Path, help='Canonical vault checkout; omit for local snapshot')
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
snapshot = root / 'packages/ui/src/brand-tokens.json'
source = args.source / 'brand/tokens.json' if args.source else snapshot
tokens = json.loads(source.read_text())
payload = json.dumps(tokens, indent=2) + '\n'
colors = tokens['colors']
css = {'accent-red': colors['accent_red'], 'accent-red-dim': colors['accent_red'] + '26', 'on-accent': colors['ink'], 'surface': colors['ink'], 'surface-border': colors['surface_border'], 'surface-card': colors['surface_card'], 'surface-elevated': colors['surface_elevated'], 'text-muted': colors['text_muted'], 'text-primary': colors['white'], 'text-secondary': colors['text_secondary']}
css = '@import "./fonts.css";\n/* Generated by scripts/sync-brand.py; edit the canonical brand tokens. */\n@theme {\n' + ''.join(f'  --color-{name}: {value.lower()};\n' for name, value in css.items()) + '  --font-sans: "Space Grotesk", system-ui, sans-serif;\n  --font-mono: var(--font-jetbrains-mono, monospace);\n}\n'
mark = tokens['thumbnail']['signature']
w, h = tokens['thumbnail']['reference_canvas']
css += ':root {\n' + f"  --thumbnail-signature-width: {mark['width'] / w * 100:g}%;\n  --thumbnail-signature-right: {mark['inset_right'] / w * 100:g}%;\n  --thumbnail-signature-bottom: {mark['inset_bottom'] / h * 100:.6f}%;\n" + '}\n'
outputs = {snapshot: payload, root / 'packages/ui/src/theme.css': css}
errors = []
for path, content in outputs.items():
    if args.check:
        if not path.is_file() or (json.loads(path.read_text()) != tokens if path.suffix == '.json' else re.sub(r'\s+', '', path.read_text()).lower() != re.sub(r'\s+', '', content).lower()):
            errors.append(f'Generated brand drift: {path.relative_to(root)}')
    else:
        path.write_text(content)
if args.check:
    manifest = json.loads((root / 'packages/ui/src/fonts/manifest.json').read_text())
    if manifest['family'] != tokens['typography']['body']:
        errors.append('Bundled font family differs from the canonical typography.')
    font_css = (root / 'packages/ui/src/fonts.css').read_text()
    if font_css.count('font-family: "' + manifest['family'] + '"') != 3:
        errors.append('Shared font-face family drift.')
    for name, digest in manifest['files'].items():
        if hashlib.sha256((root / 'packages/ui/src/fonts' / name).read_bytes()).hexdigest() != digest:
            errors.append(f'Font asset drift: {name}')
    allowed_colors = {
        'apps/app/src/components/trends/SourceLogo.tsx': {'#ff6600', '#ff4500', '#ff0000'},
        'apps/app/src/components/DashboardClient.tsx': {'#22c55e', '#f59e0b', '#8b5cf6'},
        'apps/app/src/components/livestreams/TopicDrawingBoard.tsx': {'#000000'},
        'apps/app/src/app/(public)/home.module.scss': {'#0009'},
    }
    for base in ('apps/app/src', 'apps/desktop/src', 'apps/web/src', 'packages/ui/src'):
        for path in (root / base).rglob('*'):
            if path.suffix not in ('.tsx', '.ts', '.css', '.scss'):
                continue
            text = path.read_text()
            relative = str(path.relative_to(root))
            if relative != 'packages/ui/src/theme.css' and not re.search(r'\.(test|spec)\.', path.name):
                unknown = set(re.findall(r'#[a-f0-9]{3,8}\b', text, re.I)) - allowed_colors.get(relative, set())
                if unknown:
                    errors.append(f'Hardcoded visual color outside documented semantic/vendor exceptions: {relative}: {sorted(unknown)}')
            if 'Ship Shit Show' in text:
                errors.append(f'Obsolete display-name spelling: {relative}')
            if re.search(r'#(?:ff2d20|ff5a5f)\b|rgba?\(255,\s*90,\s*95', text, re.I):
                errors.append(f'Obsolete brand color: {path.relative_to(root)}')
            if 'bg-accent-red' in text and 'text-on-accent' in text and re.search(r'bg-accent-red[^\n]*text-on-accent[^\n]*(?:hover:opacity-|hover:bg-accent-red/)', text):
                errors.append(f'Primary hover darkens contrast: {relative}')
            if re.search(r'bg-accent-red[^"\n]*text-white|text-white[^"\n]*bg-accent-red', text):
                errors.append(f'White-on-red action contrast: {path.relative_to(root)}')
    icon = ET.parse(root / 'apps/app/src/app/icon.svg').getroot()
    if {node.attrib['fill'].upper() for node in icon.iter() if 'fill' in node.attrib} != {colors['ink'], colors['accent_red']}:
        errors.append('Favicon palette differs from the show brand.')
    profiles = list((root / 'skills').glob('*/references/channel-profile.md'))
    lock = json.loads((root / 'skills/content-skills.lock.json').read_text())
    for profile in profiles:
        skill = profile.parents[1].name
        if hashlib.sha256(profile.read_bytes()).hexdigest() != lock[skill]['profile_sha256']:
            errors.append(f'Bundled profile hash drift: {skill}')
        if profile.read_bytes() != profiles[0].read_bytes():
            errors.append(f'Bundled profiles disagree: {skill}')
        text = profile.read_text()
        if 'bottom-right' not in text or '**`SH*W`**' in text:
            errors.append(f'Obsolete bundled brand profile: {profile.relative_to(root)}')
    home = (root / 'apps/app/src/app/(public)/home.module.scss').read_text()
    if re.search(r'--(?:ink|paper|red|muted|line):\s*#', home):
        errors.append('Homepage has a separate hardcoded brand palette.')
    globals_css = (root / 'apps/app/src/app/globals.scss').read_text()
    if re.search(r'--color-(?:surface|text-muted)\s*:', globals_css):
        errors.append('App shell overrides shared theme tokens.')
if errors:
    raise SystemExit('\n'.join(errors))
print('Shared web tokens and brand consumers are synchronized.')
